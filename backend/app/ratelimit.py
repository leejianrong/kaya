"""Application rate limiting (KAY-169) — one classifying middleware, mirroring pandan's V27.

Three tiers, each a `limits` rate string from `Settings` (`KAYA_RATE_LIMIT_<TIER>`):

- **auth** — the unauthenticated doors that mint a first credential: the GitHub callback, the
  device flow (`/auth/device/code`, `/auth/device/token`), RFC 7591 registration and
  `GET /auth/authorize`. Credential brute force and code-guessing live here.
- **write** — every mutating `/api/v1` request. Note creation, edit, move and delete, token
  minting, and the folder move.
- **expensive** — the DB- or upstream-heavy reads: `GET /api/v1/notes?q=` (full-text search),
  `/api/v1/graph`, and a note's `/links` (which may call pandan).

**A middleware, not slowapi decorators**, for pandan's reason: the sign-in routes are generated by
fastapi-users and cannot be decorated, and decorating every writer would churn dozens of signatures.
We still ride slowapi, whose `Limiter` holds the `limits` strategy and storage we call directly.

**Storage is in-memory** (`memory://`): a window is per process, so with N machines the effective
limit is N times what is configured, and it resets on a restart. The accepted tradeoff, as in
pandan.

**Keying.** The real client IP is Fly's `Fly-Client-IP`, never `X-Forwarded-For`: the image runs
uvicorn with `--forwarded-allow-ips=*`, so XFF is caller-spoofable. Off Fly it falls back to the
socket peer. A hash of the bearer or the session cookie is folded in as a **principal hint**
(no database lookup), so two agents behind one NAT get separate buckets. The hint is a hash and is
never logged; nothing here reads or stores the credential itself.

**Off unless `KAYA_RATE_LIMIT_ENABLED`**, and then a pure pass-through. Over the limit is `429`
`{"error": {"code": "rate_limited", …}}` with `Retry-After`, in the shape of every other refusal.
"""

import hashlib
import logging
import math
import time
from dataclasses import dataclass

from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse
from limits import RateLimitItem, parse
from slowapi import Limiter

from app.auth.errors import error_body
from app.config import Settings, get_settings
from app.identity.backend import COOKIE_NAME

logger = logging.getLogger("kaya.ratelimit")

TIERS = ("auth", "write", "expensive")

_DEFAULT_LIMITS = {
    "auth": "30/minute",
    "write": "300/minute",
    "expensive": "120/minute",
}

_WRITE_METHODS = frozenset({"POST", "PATCH", "PUT", "DELETE"})

_AUTH_ROUTES = frozenset(
    {
        ("POST", "/auth/login"),
        ("GET", "/auth/github/callback"),
        ("POST", "/auth/device/code"),
        ("POST", "/auth/device/token"),
        ("POST", "/auth/register"),
        ("GET", "/auth/authorize"),
    }
)


def classify(request: Request) -> str | None:
    """Map a request to its tier, or `None` for an unlimited route. The expensive reads are checked
    before the write catch-all only for symmetry with pandan; the two never overlap, since one is
    GET and the other a mutation."""
    path = request.url.path
    method = request.method

    if (method, path) in _AUTH_ROUTES:
        return "auth"

    if path.startswith("/api/v1"):
        if method == "GET":
            if path == "/api/v1/notes" and "q" in request.query_params:
                return "expensive"
            if path == "/api/v1/graph" or path.endswith("/links"):
                return "expensive"
            return None
        if method in _WRITE_METHODS:
            return "write"
    return None


def client_ip(request: Request) -> str:
    fly = request.headers.get("fly-client-ip")
    if fly:
        return fly.strip()
    client = request.client
    return client.host if client is not None else "unknown"


def principal_hint(request: Request) -> str:
    auth = request.headers.get("authorization")
    if auth and auth.lower().startswith("bearer "):
        return "t:" + hashlib.sha256(auth[7:].strip().encode()).hexdigest()[:16]
    cookie = request.cookies.get(COOKIE_NAME)
    if cookie:
        return "c:" + hashlib.sha256(cookie.encode()).hexdigest()[:16]
    return "anon"


@dataclass
class RateLimitEngine:
    enabled: bool
    limiter: Limiter
    items: dict[str, RateLimitItem]


def _parse_limit(tier: str, value: str) -> RateLimitItem:
    """A malformed value falls back to the tier default: a bad env var must not stop the boot."""
    try:
        return parse(value)
    except ValueError:
        logger.warning("invalid rate limit for %s: %r; using default", tier, value)
        return parse(_DEFAULT_LIMITS[tier])


def build_engine(*, enabled: bool, limits_map: dict[str, str] | None = None) -> RateLimitEngine:
    """A **fresh** in-memory store each call. `limits_map` overrides individual tiers, so a test can
    set a deterministically low bound."""
    merged = {**_DEFAULT_LIMITS, **(limits_map or {})}
    # `key_func` is never invoked: we call the strategy directly with our own identifiers.
    limiter = Limiter(key_func=lambda: "unused", strategy="moving-window", storage_uri="memory://")
    return RateLimitEngine(
        enabled=enabled,
        limiter=limiter,
        items={tier: _parse_limit(tier, value) for tier, value in merged.items()},
    )


def build_engine_from_settings(settings: Settings) -> RateLimitEngine:
    return build_engine(
        enabled=settings.rate_limit_enabled,
        limits_map={
            "auth": settings.rate_limit_auth,
            "write": settings.rate_limit_write,
            "expensive": settings.rate_limit_expensive,
        },
    )


# Consulted live on each request, so a test can swap in a low-limit engine without a rebuild.
_engine: RateLimitEngine | None = None


def current_engine() -> RateLimitEngine | None:
    return _engine


def set_engine(engine: RateLimitEngine | None) -> None:
    global _engine
    _engine = engine


def _too_many(engine: RateLimitEngine, item: RateLimitItem, *ids: str) -> JSONResponse:
    try:
        stats = engine.limiter.limiter.get_window_stats(item, *ids)
        retry_after = max(1, math.ceil(stats.reset_time - time.time()))
    except Exception:
        retry_after = item.get_expiry()
    return JSONResponse(
        status_code=429,
        content=error_body("rate_limited", "rate limit exceeded; retry later"),
        headers={"Retry-After": str(retry_after)},
    )


def install_rate_limiting(app: FastAPI) -> None:
    """Build the engine from `Settings` and register the one middleware. Always registered, and a
    pass-through while disabled."""
    set_engine(build_engine_from_settings(get_settings()))

    @app.middleware("http")
    async def _rate_limit(request: Request, call_next):  # pyright: ignore[reportUnusedFunction]
        engine = _engine
        if engine is None or not engine.enabled:
            return await call_next(request)
        tier = classify(request)
        if tier is None:
            return await call_next(request)
        item = engine.items[tier]
        ids = (tier, client_ip(request), principal_hint(request))
        if not engine.limiter.limiter.hit(item, *ids):
            return _too_many(engine, item, *ids)
        return await call_next(request)
